# Evaluation: Bumblebid (NS) vs bid_v2 (EW)
# ---------------------------------------------------------------------------
@torch.no_grad()
def evaluate(model, pool_dealers, pool_primary, pool_suits, pool_dd, device,
             n_deals=2000, opponent=None, pool_hands=None, verbose=False):
    """Evaluate Bumblebid (NS) vs opponent (EW). Returns mean NS reward.

    If no opponent, falls back to self-play (all 4 seats = Bumblebid).
    """
    env = BiddingEnv()
    total_reward = 0.0
    rng = np.random.default_rng(99)
    n_void = 0
    n_ns_bid = 0
    n_ew_bid = 0
    ns_contracts = []
    ew_contracts = []

    for _ in range(n_deals):
        idx = rng.integers(len(pool_dealers))
        dealer = int(pool_dealers[idx])
        dd = pool_dd[idx].tolist()

        env.dealer = dealer
        env.dd_pts = dd
        env.bid_history = []
        env.current_player_seat = (dealer + 1) % 4
        env.consecutive_passes = 0
        env.current_bid = None
        env.coinche_level = 0
        env.done = False

        ns_bid_this = False
        ew_bid_this = False

        while not env.done:
            seat = env.current_player_seat
            is_ew = seat % 2 == 1
            mask = env.legal_actions_mask()

            if is_ew and opponent is not None and pool_hands is not None:
                # Opponent (bid_v2) plays for EW
                obs = build_bid_obs_batch(
                    pool_hands[idx:idx+1],
                    np.array([seat]),
                    np.array([dealer]),
                    [env.bid_history],
                    np.array([0]),
                )
                obs_t = torch.from_numpy(obs).to(device)
                m_t = torch.from_numpy(mask).unsqueeze(0).to(device)
                with torch.amp.autocast("cuda", dtype=torch.bfloat16):
                    q = opponent(obs_t)
                q = q.float().masked_fill(m_t == 0, -1e9)
                action = q.argmax(dim=-1).item()
            else:
                # Bumblebid plays for NS (or self-play fallback)
                hp = pool_primary[idx, seat]
                hs = pool_suits[idx, seat]
                primary = list(hp.astype(np.int64))
                suits = list(hs.astype(np.int64))
                for _s, act in env.bid_history:
                    if len(primary) + 2 > MAX_SEQ_LEN:
                        break
                    primary.extend([int(ACTION_PRIMARY_LUT[act]), P_NONE])
                    suits.extend([int(ACTION_SUIT_LUT[act]), int(ACTION_SUIT2_LUT[act])])

                p_t = torch.tensor(primary[:MAX_SEQ_LEN], dtype=torch.long, device=device).unsqueeze(0)
                s_t = torch.tensor(suits[:MAX_SEQ_LEN], dtype=torch.long, device=device).unsqueeze(0)
                m_t = torch.from_numpy(mask).unsqueeze(0).to(device)
                with torch.amp.autocast("cuda", dtype=torch.bfloat16):
                    logits = model(p_t, s_t)
                logits = logits.float().masked_fill(m_t == 0, -1e9)
                action = logits.argmax(dim=-1).item()

            # Track who bid
            if action >= 1 and action <= 40:
                if is_ew:
                    ew_bid_this = True
                else:
                    ns_bid_this = True

            env.step(action)

        if env.current_bid is None:
            n_void += 1
        else:
            val_enc, suit, taker_team = env.current_bid
            if taker_team == 0:
                ns_contracts.append(val_enc * 10)
            else:
                ew_contracts.append(val_enc * 10)
        if ns_bid_this:
            n_ns_bid += 1
        if ew_bid_this:
            n_ew_bid += 1

        ns_r, _ = env.compute_reward()
        total_reward += ns_r

    mean_r = total_reward / n_deals
    if verbose:
        void_pct = 100.0 * n_void / n_deals
        ns_bid_pct = 100.0 * n_ns_bid / n_deals
        ew_bid_pct = 100.0 * n_ew_bid / n_deals
        ns_take_pct = 100.0 * len(ns_contracts) / n_deals if n_deals > 0 else 0
        ew_take_pct = 100.0 * len(ew_contracts) / n_deals if n_deals > 0 else 0
        ns_mean_cv = np.mean(ns_contracts) if ns_contracts else 0
        ew_mean_cv = np.mean(ew_contracts) if ew_contracts else 0
        print(f"        void={void_pct:.1f}%  NS_bid={ns_bid_pct:.1f}%  EW_bid={ew_bid_pct:.1f}%  "
              f"NS_take={ns_take_pct:.1f}%(avg {ns_mean_cv:.0f})  EW_take={ew_take_pct:.1f}%(avg {ew_mean_cv:.0f})",
              flush=True)
    return mean_r


def _save_model(model, path):
    """Save model state dict, stripping torch.compile prefix if present."""
    sd = model.state_dict()
    sd = {k.replace("_orig_mod.", ""): v for k, v in sd.items()}
    torch.save(sd, path)


