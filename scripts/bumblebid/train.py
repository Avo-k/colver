BID_PASS = 0
BID_COINCHE = 41
BID_SURCOINCHE = 42

# Bid value/suit lookup for legal mask computation
_BID_VAL_LUT = np.zeros(41, dtype=np.int32)
_BID_SUIT_LUT = np.zeros(41, dtype=np.int32)
for _a in range(1, 41):
    if _a <= 36:
        _BID_VAL_LUT[_a] = (_a - 1) // 4 + 8
        _BID_SUIT_LUT[_a] = (_a - 1) % 4
    else:
        _BID_VAL_LUT[_a] = 25
        _BID_SUIT_LUT[_a] = _a - 37


# ---------------------------------------------------------------------------
# GPU replay buffer
# ---------------------------------------------------------------------------
class GPUReplayBuffer:
    """Circular replay buffer living entirely on GPU."""

    def __init__(self, capacity, device):
        self.capacity = capacity
        self.device = device
        self.primary = torch.zeros(capacity, MAX_SEQ_LEN, dtype=torch.long, device=device)
        self.suits = torch.zeros(capacity, MAX_SEQ_LEN, dtype=torch.long, device=device)
        self.seq_lens = torch.zeros(capacity, dtype=torch.long, device=device)
        self.masks = torch.zeros(capacity, NUM_BID_ACTIONS, dtype=torch.float32, device=device)
        self.actions = torch.zeros(capacity, dtype=torch.long, device=device)
        self.rewards = torch.zeros(capacity, dtype=torch.float32, device=device)
        self.size = 0
        self.pos = 0

    def sample(self, batch_size):
        """Sample a random batch — already on GPU, no transfer needed."""
        idx = torch.randint(self.size, (batch_size,), device=self.device)
        max_len = self.seq_lens[idx].max().item()
        return {
            "primary": self.primary[idx, :max_len],
            "suits": self.suits[idx, :max_len],
            "seq_lens": self.seq_lens[idx],
            "masks": self.masks[idx],
            "actions": self.actions[idx],
            "rewards": self.rewards[idx],
        }


