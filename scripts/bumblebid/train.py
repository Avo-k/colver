# Arena evaluation: full games (bid + DouDou50 play) via PyO3 Env
# ---------------------------------------------------------------------------
@torch.no_grad()
def arena_evaluate(model, device, bid_model_path, play_model_path, n_matches=100):
    """Run n_matches duplicate matches: Bumblebid vs bid_v2, both using DouDou50.
    Returns (bb_wins, v2_wins, avg_diff).
    """
    try:
        from colver import Env
    except ImportError:
        return None

    bb_total = 0.0
    v2_total = 0.0
    bb_wins = 0
    v2_wins = 0

    for i in range(n_matches):
        # Direction A: BB = NS
        env_a = Env()
        env_a.reset()
        env_a.load_bid_model(bid_model_path, 512)
        env_a.load_dmc_model(play_model_path)
        hands = env_a.get_hands()
        dealer = env_a.get_dealer()

        ns_a, ew_a = _arena_play_game(env_a, model, 0, device)

        # Direction B: BB = EW (same deal)
        env_b = Env.deal_with_hands(dealer, hands)
        env_b.load_bid_model(bid_model_path, 512)
        env_b.load_dmc_model(play_model_path)

        ns_b, ew_b = _arena_play_game(env_b, model, 1, device)

        bb_score = ns_a + ew_b
        v2_score = ew_a + ns_b
        bb_total += bb_score
        v2_total += v2_score
        if bb_score > v2_score:
            bb_wins += 1
        elif v2_score > bb_score:
            v2_wins += 1

    avg_diff = (bb_total - v2_total) / n_matches
    return bb_wins, v2_wins, n_matches, avg_diff


def _arena_play_game(env, model, bb_team, device):
    """Play one full game. bb_team: 0=NS, 1=EW."""
    while env.phase() == 0 and not env.is_terminal():
        seat = env.current_player()
        if seat % 2 == bb_team:
            action = _arena_bb_action(env, model, device)
        else:
            action = env.action_bid_nn()["best_action"]
        env.step(action)
    while not env.is_terminal():
        action = env.action_dmc_with_stats()["best_action"]
        env.step(action)
    return env.rewards()


def _arena_bb_action(env, model, device):
    """Get Bumblebid action from Env state."""
    seat = env.current_player()
    dealer = env.get_dealer()
    hand_cards = env.get_hands()[seat]
    bid_history = env.get_bid_history()

    cards = [(c % 8, c // 8) for c in hand_cards]
    cards.sort(key=lambda c: c[1] * 8 + c[0])

    pos = (seat + 4 - dealer) % 4
    primary = [P_CLS, P_POS0 + pos]
    suits = [S_NULL, S_NULL]
    for rank, suit in cards:
        primary.append(P_RANK0 + rank)
        suits.append(suit)
    for _s, act in bid_history:
        if len(primary) + 2 > MAX_SEQ_LEN:
            break
        primary.extend([int(ACTION_PRIMARY_LUT[act]), P_NONE])
        suits.extend([int(ACTION_SUIT_LUT[act]), int(ACTION_SUIT2_LUT[act])])
    while len(primary) < MAX_SEQ_LEN:
        primary.append(0)
        suits.append(0)

    p_t = torch.tensor(primary[:MAX_SEQ_LEN], dtype=torch.long, device=device).unsqueeze(0)
    s_t = torch.tensor(suits[:MAX_SEQ_LEN], dtype=torch.long, device=device).unsqueeze(0)
    mask = env.legal_action_mask()
    m_t = torch.from_numpy(mask[:43]).unsqueeze(0).to(device)
    with torch.amp.autocast("cuda", dtype=torch.bfloat16):
        logits = model(p_t, s_t)
    logits = logits.float().masked_fill(m_t == 0, -1e9)
    return logits.argmax(dim=-1).item()


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    p = argparse.ArgumentParser(description="Train Bumblebid (self-play)")
    p.add_argument("--pool-file", default="data/pools/bumblebid_2.5M.bin")
    p.add_argument("--d-model", type=int, default=256)
    p.add_argument("--n-layers", type=int, default=4)
    p.add_argument("--n-heads", type=int, default=8)
    p.add_argument("--n-envs", type=int, default=512)
    p.add_argument("--steps", type=int, default=2_000_000)
    p.add_argument("--batch-size", type=int, default=1024)
    p.add_argument("--lr", type=float, default=3e-4)
    p.add_argument("--buffer-size", type=int, default=2_000_000)
    p.add_argument("--min-buffer", type=int, default=10_000)
    p.add_argument("--train-freq", type=int, default=4)
    p.add_argument("--eps-start", type=float, default=1.0)
    p.add_argument("--eps-end", type=float, default=0.05)
    p.add_argument("--eps-decay-steps", type=int, default=500_000)
    p.add_argument("--weight-decay", type=float, default=0.01)
    p.add_argument("--eval-freq", type=int, default=50_000)
    p.add_argument("--save-freq", type=int, default=500_000)
    p.add_argument("--save-dir", default="models/bumblebid")
    p.add_argument("--seed", type=int, default=42)
    p.add_argument("--compile", action="store_true", help="torch.compile with CUDA graphs")
    p.add_argument("--opponent", type=str, default=None,
                   help="Path to bid_v2 .bin weights for EW opponent")
    p.add_argument("--opponent-ratio", type=float, default=1.0,
                   help="Fraction of steps using opponent (decays to 0)")
    p.add_argument("--opponent-decay-steps", type=int, default=1_000_000,
                   help="Steps over which opponent ratio decays to 0")
    p.add_argument("--nn-team-only", action="store_true",
                   help="Only store NN team (NS) transitions in replay buffer")
    p.add_argument("--dd-pool", type=str, default="data/pools/dd_2.5M.bin",
                   help="Original DD pool (needed for opponent obs)")
    p.add_argument("--reward-mix", type=float, default=1.0,
                   help="Reward mix: 1.0=100%% DD, 0.0=100%% real, 0.5=50/50")
    p.add_argument("--arena-freq", type=int, default=0,
                   help="Run arena eval every N steps (0=disabled). Needs --arena-bid-model and --arena-play-model")
    p.add_argument("--arena-bid-model", type=str, default="models/bid_v2/bid_nn_final.bin")
    p.add_argument("--arena-play-model", type=str, default="models/dmc_50.bin")
    p.add_argument("--arena-matches", type=int, default=100,
                   help="Number of duplicate matches per arena eval")
    args = p.parse_args()

    torch.manual_seed(args.seed)
    np.random.seed(args.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    save_dir = Path(args.save_dir)
    save_dir.mkdir(parents=True, exist_ok=True)

    # Performance: TF32 matmuls (free precision is fine for training)
    torch.set_float32_matmul_precision("high")
    torch.backends.cudnn.benchmark = True

    dealers, hand_primary, hand_suits, dd_pts, real_pts = load_bumblebid_pool(args.pool_file)
    gpu_mb = (hand_primary.size + hand_suits.size) * 8 / 1e6
    print(f"Pool: {len(dealers):,} deals, GPU: ~{gpu_mb:.0f} MB", flush=True)

    # Load opponent if specified
    opponent_model = None
    pool_hands = None
    if args.opponent:
        opponent_model = BidNetV2.load_from_bin(args.opponent).to(device)
        opponent_model.eval()
        for p_ in opponent_model.parameters():
            p_.requires_grad_(False)
        print(f"Opponent: {args.opponent} ({sum(p_.numel() for p_ in opponent_model.parameters()):,} params)", flush=True)
        _, pool_hands, _ = load_dd_pool(args.dd_pool)
        print(f"Opponent ratio: {args.opponent_ratio} → 0 over {args.opponent_decay_steps:,} steps", flush=True)

    model = Bumblebid(
        d_model=args.d_model, n_layers=args.n_layers, n_heads=args.n_heads,
    ).to(device)
    n_params = sum(pp.numel() for pp in model.parameters())

    # torch.compile with CUDA graphs for maximum throughput
    if args.compile:
        print("Compiling model (reduce-overhead)...", flush=True)
        model = torch.compile(model, mode="reduce-overhead", fullgraph=True)

    print(f"Bumblebid: {n_params:,} params  d={args.d_model} L={args.n_layers} H={args.n_heads}", flush=True)
    print(f"Envs: {args.n_envs}  Steps: {args.steps:,}  LR: {args.lr}", flush=True)
    print(f"Buffer: {args.buffer_size:,} (GPU)  Batch: {args.batch_size}  Train freq: {args.train_freq}", flush=True)
    print(f"Epsilon: {args.eps_start}->{args.eps_end} over {args.eps_decay_steps:,}", flush=True)
    compile_str = "compile+bf16" if args.compile else "eager"
    print(f"Device: {device}  Mode: {compile_str}", flush=True)

    optimizer = torch.optim.AdamW(
        model.parameters(), lr=args.lr, weight_decay=args.weight_decay,
        betas=(0.9, 0.98), fused=True,
    )

    if real_pts is not None and args.reward_mix < 1.0:
        print(f"Reward mix: {args.reward_mix:.2f} (DD={args.reward_mix:.0%}, real={1-args.reward_mix:.0%})", flush=True)
    else:
        if args.reward_mix < 1.0:
            print("WARNING: --reward-mix < 1.0 but pool has no real_pts, using 100% DD", flush=True)
        args.reward_mix = 1.0

    nn_team_only = args.nn_team_only or (opponent_model is not None)
    if nn_team_only and opponent_model is not None:
        print(f"Replay filter: NN team (NS) only", flush=True)

    vec_env = VecBiddingEnv(
        args.n_envs, dealers, hand_primary, hand_suits, dd_pts, device, seed=args.seed,
        pool_hands=pool_hands, opponent=opponent_model,
        pool_real=real_pts, reward_mix=args.reward_mix, nn_team_only=nn_team_only,
    )
    replay_buffer = GPUReplayBuffer(args.buffer_size, device)

    print(
        f"\n{'Step':>10} | {'Eps':>5} | {'Buffer':>7} | {'Loss':>8} | "
        f"{'Episodes':>8} | {'EvalR':>7} | {'Steps/s':>7}",
        flush=True,
    )
    print("-" * 72, flush=True)

    total_episodes = 0
    total_loss = 0.0
    loss_count = 0
    last_log_step = 0
    last_log_time = time.time()

    for step in range(args.steps):
        eps = args.eps_start + (args.eps_end - args.eps_start) * min(step / args.eps_decay_steps, 1.0)

        # Self-play step
        primary, suits, pad_mask = vec_env.get_batch()
        masks_np = vec_env.compute_legal_masks()
        action_mask = torch.from_numpy(masks_np).to(device)
        actions = select_actions(model, primary, suits, pad_mask, action_mask, eps)

        # Use opponent for EW seats (with curriculum decay)
        if opponent_model is not None:
            opp_ratio = args.opponent_ratio * max(0, 1.0 - step / args.opponent_decay_steps)
            if opp_ratio > 0 and np.random.random() < opp_ratio:
                opp_result = vec_env.get_opponent_actions(masks_np)
                if opp_result is not None:
                    opp_actions, is_ew = opp_result
                    actions[is_ew] = opp_actions[is_ew]

        completed = vec_env.step_all(actions, masks_np, replay_buffer)
        total_episodes += completed

        # Training step
        if replay_buffer.size >= args.min_buffer and step % args.train_freq == 0:
            batch = replay_buffer.sample(args.batch_size)
            augment_batch(batch, device)
            max_len = batch["primary"].shape[1]
            # Pad to bucket for CUDA graph reuse
            for bk in [10, 16, 24, 34]:
                if bk >= max_len:
                    max_len = bk
                    break
            if max_len > batch["primary"].shape[1]:
                pad_cols = max_len - batch["primary"].shape[1]
                z = torch.zeros(args.batch_size, pad_cols, dtype=torch.long, device=device)
                batch["primary"] = torch.cat([batch["primary"], z], dim=1)
                batch["suits"] = torch.cat([batch["suits"], z], dim=1)
            pad_mask_b = torch.arange(max_len, device=device).unsqueeze(0) >= batch["seq_lens"].unsqueeze(1)

            with torch.amp.autocast("cuda", dtype=torch.bfloat16):
                logits = model(batch["primary"], batch["suits"], pad_mask_b)
                q_taken = logits.gather(1, batch["actions"].unsqueeze(1)).squeeze(1)
                loss = F.mse_loss(q_taken, batch["rewards"])

            optimizer.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            total_loss += loss.item()
            loss_count += 1

        # Logging
        if (step + 1) % 10_000 == 0:
            elapsed = time.time() - last_log_time
            sps = (step + 1 - last_log_step) / max(elapsed, 1e-6)
            avg_loss = total_loss / max(loss_count, 1)
            print(
                f"{step+1:10,} | {eps:5.3f} | {replay_buffer.size:7,} | "
                f"{avg_loss:8.5f} | {total_episodes:8,} | {'--':>7} | {sps:7.0f}",
                flush=True,
            )
            total_loss = 0.0
            loss_count = 0
            last_log_step = step + 1
            last_log_time = time.time()

        if (step + 1) % args.eval_freq == 0:
            eval_r = evaluate(
                model, dealers, hand_primary, hand_suits, dd_pts, device,
                opponent=opponent_model, pool_hands=pool_hands, verbose=True,
            )
            label = "vs bid_v2" if opponent_model else "self-play"
            print(f"  >>> Eval ({label}): {eval_r:+.4f}", flush=True)
            _save_model(model, save_dir / "latest.pt")

        if args.arena_freq > 0 and (step + 1) % args.arena_freq == 0:
            result = arena_evaluate(
                model, device, args.arena_bid_model, args.arena_play_model,
                n_matches=args.arena_matches,
            )
            if result is not None:
                bb_w, v2_w, n, diff = result
                print(f"  >>> Arena ({n} matches): BB={bb_w} V2={v2_w} diff={diff:+.1f}", flush=True)

        if (step + 1) % args.save_freq == 0:
            _save_model(model, save_dir / f"step_{step+1}.pt")

    _save_model(model, save_dir / "final.pt")
    print(f"\nDone. Episodes: {total_episodes:,}", flush=True)


if __name__ == "__main__":
    main()
