# Vectorized bidding environment
# ---------------------------------------------------------------------------
MAX_EP_STEPS = 48  # max transitions per auction (40 bids + passes + coinche)


class VecBiddingEnv:
    """Fully vectorized N-env bidding environment.

    Pool tokens on GPU, env state + episode buffers in numpy (vectorized).
    Replay buffer on GPU — flush writes directly to device.
    """

    def __init__(self, n_envs, pool_dealers, pool_primary, pool_suits, pool_dd,
                 device, seed=42, pool_hands=None, opponent=None,
                 pool_real=None, reward_mix=1.0, nn_team_only=False):
        self.n = n_envs
        self.pool_dealers = pool_dealers
        self.pool_dd = pool_dd
        self.pool_real = pool_real  # [N_pool, 4] uint8 or None
        self.reward_mix = reward_mix  # 1.0=DD, 0.0=real, 0.5=blend
        self.nn_team_only = nn_team_only  # if True, only store NN team (NS=0) in replay
        self.n_pool = len(pool_dealers)
        self.rng = np.random.default_rng(seed)
        self.device = device

        # Opponent model (bid_v2) — None means pure self-play
        self.opponent = opponent
        self.pool_hands = pool_hands  # [N_pool, 4] uint32, needed for opponent obs

        # Pre-tokenized hands on GPU: [N_pool, 4, 10]
        self.gpu_primary = torch.from_numpy(pool_primary.astype(np.int64)).to(device)
        self.gpu_suits = torch.from_numpy(pool_suits.astype(np.int64)).to(device)
        # CPU copy for replay buffer (avoid GPU→CPU per transition)
        self.cpu_primary = torch.from_numpy(pool_primary.astype(np.int64))
        self.cpu_suits = torch.from_numpy(pool_suits.astype(np.int64))

        # Per-env state (numpy, vectorized)
        self.deal_idx = np.zeros(n_envs, dtype=np.int64)
        self.env_dealer = np.zeros(n_envs, dtype=np.int32)
        self.env_dd = np.zeros((n_envs, 4), dtype=np.uint8)
        self.env_cur_player = np.zeros(n_envs, dtype=np.int32)
        self.env_consec_passes = np.zeros(n_envs, dtype=np.int32)
        self.env_bid_val = np.full(n_envs, -1, dtype=np.int32)
        self.env_bid_suit = np.zeros(n_envs, dtype=np.int32)
        self.env_bid_team = np.zeros(n_envs, dtype=np.int32)
        self.env_coinche = np.zeros(n_envs, dtype=np.int32)
        self.env_done = np.zeros(n_envs, dtype=bool)

        # Bid tokens (numpy, transferred to GPU in get_batch)
        self.bid_primary = np.zeros((n_envs, 24), dtype=np.int64)
        self.bid_suits = np.zeros((n_envs, 24), dtype=np.int64)
        self.n_bid_tokens = np.zeros(n_envs, dtype=np.int32)

        # Bid history as (seat, action) pairs — needed for opponent obs
        self.bid_history_seats = np.zeros((n_envs, MAX_EP_STEPS), dtype=np.int32)
        self.bid_history_actions = np.zeros((n_envs, MAX_EP_STEPS), dtype=np.int32)
        self.bid_history_len = np.zeros(n_envs, dtype=np.int32)

        # Pre-allocated episode buffers (numpy, vectorized writes)
        self.ep_seats = np.zeros((n_envs, MAX_EP_STEPS), dtype=np.int32)
        self.ep_nb = np.zeros((n_envs, MAX_EP_STEPS), dtype=np.int32)
        self.ep_actions = np.zeros((n_envs, MAX_EP_STEPS), dtype=np.int32)
        self.ep_teams = np.zeros((n_envs, MAX_EP_STEPS), dtype=np.int32)
        self.ep_masks = np.zeros((n_envs, MAX_EP_STEPS, NUM_BID_ACTIONS), dtype=np.float32)
        self.ep_len = np.zeros(n_envs, dtype=np.int32)

        self.reset_all()

    def reset_envs(self, indices):
        idx = np.asarray(indices)
        if len(idx) == 0:
            return
        di = self.rng.integers(self.n_pool, size=len(idx))

        self.deal_idx[idx] = di
        self.env_dealer[idx] = self.pool_dealers[di]
        self.env_dd[idx] = self.pool_dd[di]
        self.env_cur_player[idx] = (self.pool_dealers[di] + 1) % 4
        self.env_consec_passes[idx] = 0
        self.env_bid_val[idx] = -1
        self.env_bid_suit[idx] = 0
        self.env_bid_team[idx] = 0
        self.env_coinche[idx] = 0
        self.env_done[idx] = False
        self.bid_primary[idx] = 0
        self.bid_suits[idx] = 0
        self.n_bid_tokens[idx] = 0
        self.bid_history_len[idx] = 0
        self.ep_len[idx] = 0

    def reset_all(self):
        self.reset_envs(np.arange(self.n))

    # Fixed bucket sizes for CUDA graph compatibility (avoid dynamic shapes)
    _SEQ_BUCKETS = [10, 16, 24, 34]

    def get_batch(self):
        """Build GPU batch. Returns (primary, suits, pad_mask) on device."""
        max_nb = int(self.n_bid_tokens.max())
        raw_len = 10 + max_nb

        # Pad to next bucket for CUDA graph reuse
        seq_len = raw_len
        for b in self._SEQ_BUCKETS:
            if b >= raw_len:
                seq_len = b
                break

        # Hand tokens from GPU pool: [N, 10]
        deal_t = torch.from_numpy(self.deal_idx).to(self.device)
        seat_t = torch.from_numpy(self.env_cur_player.astype(np.int64)).to(self.device)
        hand_p = self.gpu_primary[deal_t, seat_t]
        hand_s = self.gpu_suits[deal_t, seat_t]

        if seq_len == 10:
            pad = torch.zeros(self.n, 10, dtype=torch.bool, device=self.device)
            return hand_p, hand_s, pad

        # Bid tokens: numpy → GPU
        bid_p = torch.from_numpy(self.bid_primary[:, :max_nb].copy()).to(self.device)
        bid_s = torch.from_numpy(self.bid_suits[:, :max_nb].copy()).to(self.device)

        # Pad to bucket size
        pad_cols = seq_len - 10 - max_nb
        if pad_cols > 0:
            z = torch.zeros(self.n, pad_cols, dtype=torch.long, device=self.device)
            batch_p = torch.cat([hand_p, bid_p, z], dim=1)
            batch_s = torch.cat([hand_s, bid_s, z], dim=1)
        else:
            batch_p = torch.cat([hand_p, bid_p], dim=1)
            batch_s = torch.cat([hand_s, bid_s], dim=1)

        lens = torch.from_numpy((10 + self.n_bid_tokens).astype(np.int64)).to(self.device)
        positions = torch.arange(seq_len, device=self.device).unsqueeze(0)
        pad_mask = positions >= lens.unsqueeze(1)

        return batch_p, batch_s, pad_mask

    def compute_legal_masks(self):
        """Vectorized legal masks. Returns [N, 43] float32 numpy."""
        N = self.n
        masks = np.zeros((N, NUM_BID_ACTIONS), dtype=np.float32)
        masks[:, BID_PASS] = 1.0

        no_bid = (self.env_bid_val < 0) & ~self.env_done
        masks[no_bid, 1:41] = 1.0

        has_bid = (self.env_bid_val >= 0) & ~self.env_done
        not_coinched = (self.env_coinche == 0) & has_bid
        if np.any(not_coinched):
            nc = np.where(not_coinched)[0]
            cv, cs, ct = self.env_bid_val[nc], self.env_bid_suit[nc], self.env_bid_team[nc]
            bv = _BID_VAL_LUT[1:41]
            higher = bv[None, :] > cv[:, None]
            masks[nc[:, None], np.arange(1, 41)[None, :]] = higher.astype(np.float32)
            opp = (self.env_cur_player[nc] % 2) != ct
            masks[nc[opp], BID_COINCHE] = 1.0

        coinched = (self.env_coinche == 1) & has_bid
        if np.any(coinched):
            ci = np.where(coinched)[0]
            same = (self.env_cur_player[ci] % 2) == self.env_bid_team[ci]
            masks[ci[same], BID_SURCOINCHE] = 1.0

        return masks

    @torch.no_grad()
    def get_opponent_actions(self, masks_np):
        """Compute actions for EW seats using the opponent model.
        Returns [N] actions (only meaningful where cur_player is EW).
        """
        if self.opponent is None or self.pool_hands is None:
            return None

        is_ew = (self.env_cur_player % 2 == 1) & ~self.env_done
        if not np.any(is_ew):
            return None

        ew_idx = np.where(is_ew)[0]

        # Build bid history lists for opponent obs
        histories = []
        for i in ew_idx:
            bhl = int(self.bid_history_len[i])
            h = list(zip(
                self.bid_history_seats[i, :bhl].tolist(),
                self.bid_history_actions[i, :bhl].tolist(),
            ))
            histories.append(h)

        # Build obs
        di = self.deal_idx[ew_idx]
        obs = build_bid_obs_batch(
            self.pool_hands[di],
            self.env_cur_player[ew_idx],
            self.env_dealer[ew_idx],
            histories,
            self.n_bid_tokens[ew_idx],
        )
        obs_t = torch.from_numpy(obs).to(self.device)
        mask_t = torch.from_numpy(masks_np[ew_idx]).to(self.device)

        with torch.amp.autocast("cuda", dtype=torch.bfloat16):
            q = self.opponent(obs_t)
        q = q.float().masked_fill(mask_t == 0, -1e9)
        opp_actions = q.argmax(dim=-1).cpu().numpy()

        # Build full action array
        result = np.zeros(self.n, dtype=np.int32)
        result[ew_idx] = opp_actions
        return result, is_ew

    def step_all(self, actions, masks_np, replay_buffer):
        """Step all envs. Returns number of completed episodes."""
        # --- Vectorized snapshot (all active seats, both teams) ---
        active = ~self.env_done
        active_idx = np.where(active)[0]
        if len(active_idx) > 0:
            el = self.ep_len[active_idx]
            self.ep_seats[active_idx, el] = self.env_cur_player[active_idx]
            self.ep_nb[active_idx, el] = self.n_bid_tokens[active_idx]
            self.ep_actions[active_idx, el] = actions[active_idx]
            self.ep_teams[active_idx, el] = self.env_cur_player[active_idx] % 2
            self.ep_masks[active_idx, el] = masks_np[active_idx]
            self.ep_len[active_idx] += 1

        # --- Vectorized state update ---
        act = actions
        nb = self.n_bid_tokens.copy()
        can_append = active & (nb + 2 <= 24)
        if np.any(can_append):
            ca = np.where(can_append)[0]
            nbs = nb[ca]
            acts = act[ca]
            self.bid_primary[ca, nbs] = ACTION_PRIMARY_LUT[acts]
            self.bid_suits[ca, nbs] = ACTION_SUIT_LUT[acts]
            self.bid_primary[ca, nbs + 1] = P_NONE
            self.bid_suits[ca, nbs + 1] = ACTION_SUIT2_LUT[acts]
            self.n_bid_tokens[ca] = nbs + 2

        # Record bid history (for opponent obs)
        active_idx = np.where(active)[0]
        bhl = self.bid_history_len[active_idx]
        valid = bhl < MAX_EP_STEPS
        vi = active_idx[valid]
        vl = bhl[valid]
        self.bid_history_seats[vi, vl] = self.env_cur_player[vi]
        self.bid_history_actions[vi, vl] = act[vi]
        self.bid_history_len[vi] = vl + 1

        is_pass = (act == BID_PASS) & active
        self.env_consec_passes[is_pass] += 1

        is_coinche = (act == BID_COINCHE) & active
        self.env_coinche[is_coinche] = 1
        self.env_consec_passes[is_coinche] = 0

        is_surcoinche = (act == BID_SURCOINCHE) & active
        self.env_coinche[is_surcoinche] = 2
        self.env_consec_passes[is_surcoinche] = 0
        self.env_done[is_surcoinche] = True

        is_bid = active & (act >= 1) & (act <= 40)
        if np.any(is_bid):
            bi = np.where(is_bid)[0]
            ba = act[bi]
            self.env_bid_val[bi] = _BID_VAL_LUT[ba]
            self.env_bid_suit[bi] = _BID_SUIT_LUT[ba]
            self.env_bid_team[bi] = self.env_cur_player[bi] % 2
            self.env_coinche[bi] = 0
            self.env_consec_passes[bi] = 0

        still_active = active & ~is_surcoinche
        void_end = still_active & (self.env_bid_val < 0) & (self.env_consec_passes >= 4)
        bid_end = still_active & (self.env_bid_val >= 0) & (self.env_consec_passes >= 3)
        self.env_done[void_end | bid_end] = True

        self.env_cur_player[active] = (self.env_cur_player[active] + 1) % 4

        # --- Flush completed episodes to GPU replay buffer ---
        just_done = np.where(self.env_done & active)[0]
        completed = len(just_done)

        if completed > 0:
            self._flush_episodes(just_done, replay_buffer)
            self.reset_envs(just_done)

        return completed

    def _flush_episodes(self, done_idx, rb):
        """Write completed episodes to GPU replay buffer — fully vectorized."""
        n_done = len(done_idx)
        ep_lens = self.ep_len[done_idx]
        total = int(ep_lens.sum())
        if total == 0:
            return

        # Flat indices: env_flat[t] = which env, step_flat[t] = which step
        env_flat = np.repeat(done_idx, ep_lens)
        step_flat = np.concatenate([np.arange(l) for l in ep_lens])

        # Gather episode buffer data (all numpy, no loops)
        seats = self.ep_seats[env_flat, step_flat]       # [total]
        nbs = self.ep_nb[env_flat, step_flat]             # [total]
        acts = self.ep_actions[env_flat, step_flat]        # [total]
        teams = self.ep_teams[env_flat, step_flat]         # [total]
        masks = self.ep_masks[env_flat, step_flat]         # [total, 43]
        dis = self.deal_idx[env_flat]                      # [total]

        # Compute rewards per done env — blend DD and real points
        ns_rewards = np.zeros(n_done, dtype=np.float32)
        for k, i in enumerate(done_idx):
            if self.env_bid_val[i] >= 0:
                cv = int(self.env_bid_val[i]) * 10
                suit = int(self.env_bid_suit[i])
                team = int(self.env_bid_team[i])
                ns_dd, ew_dd = compute_deal_score(self.env_dd[i], cv, suit, team)
                if self.pool_real is not None and self.reward_mix < 1.0:
                    di = int(self.deal_idx[i])
                    real_dd = self.pool_real[di].copy()
                    ns_real, ew_real = compute_deal_score(real_dd, cv, suit, team)
                    m = self.reward_mix
                    ns_rewards[k] = (m * (ns_dd - ew_dd) + (1 - m) * (ns_real - ew_real)) / 500.0
                else:
                    ns_rewards[k] = (ns_dd - ew_dd) / 500.0

        # Map: env_flat → done_idx position
        done_k = np.repeat(np.arange(n_done), ep_lens)
        rewards_flat = np.where(teams == 0, ns_rewards[done_k], -ns_rewards[done_k])

        # Filter to NN team only (NS=0) when using opponent
        if self.nn_team_only:
            keep = teams == 0
            if not np.any(keep):
                return
            env_flat = env_flat[keep]
            step_flat = step_flat[keep]
            seats = seats[keep]
            nbs = nbs[keep]
            acts = acts[keep]
            teams = teams[keep]
            masks = masks[keep]
            dis = dis[keep]
            rewards_flat = rewards_flat[keep]
            total = int(keep.sum())

        # Build primary/suit sequences (numpy, vectorized)
        pool_p_np = self.cpu_primary.numpy()
        pool_s_np = self.cpu_suits.numpy()

        batch_p = np.zeros((total, MAX_SEQ_LEN), dtype=np.int64)
        batch_s = np.zeros((total, MAX_SEQ_LEN), dtype=np.int64)
        batch_p[:, :10] = pool_p_np[dis, seats]
        batch_s[:, :10] = pool_s_np[dis, seats]

        max_nb = int(nbs.max())
        if max_nb > 0:
            bid_p = self.bid_primary[env_flat, :max_nb]  # [total, max_nb]
            bid_s = self.bid_suits[env_flat, :max_nb]
            bid_mask = np.arange(max_nb)[None, :] < nbs[:, None]
            batch_p[:, 10:10 + max_nb] = bid_p * bid_mask
            batch_s[:, 10:10 + max_nb] = bid_s * bid_mask

        sls = (10 + nbs).astype(np.int64)

        # Single batch transfer to GPU
        all_data = torch.from_numpy(np.column_stack([
            batch_p, batch_s,
            sls[:, None],
            acts[:, None].astype(np.int64),
        ])).to(rb.device, non_blocking=True)
        masks_t = torch.from_numpy(masks).to(rb.device, non_blocking=True)
        rewards_t = torch.from_numpy(rewards_flat).to(rb.device, non_blocking=True)

        bp = all_data[:, :MAX_SEQ_LEN]
        bs = all_data[:, MAX_SEQ_LEN:2 * MAX_SEQ_LEN]
        bsl = all_data[:, 2 * MAX_SEQ_LEN].long()
        ba = all_data[:, 2 * MAX_SEQ_LEN + 1].long()

        # Write to replay buffer (handle wraparound)
        end = rb.pos + total
        if end <= rb.capacity:
            s = slice(rb.pos, end)
            rb.primary[s] = bp
            rb.suits[s] = bs
            rb.seq_lens[s] = bsl
            rb.masks[s] = masks_t
            rb.actions[s] = ba
            rb.rewards[s] = rewards_t
        else:
            first = rb.capacity - rb.pos
            rb.primary[rb.pos:] = bp[:first]
            rb.suits[rb.pos:] = bs[:first]
            rb.seq_lens[rb.pos:] = bsl[:first]
            rb.masks[rb.pos:] = masks_t[:first]
            rb.actions[rb.pos:] = ba[:first]
            rb.rewards[rb.pos:] = rewards_t[:first]
            rem = total - first
            rb.primary[:rem] = bp[first:]
            rb.suits[:rem] = bs[first:]
            rb.seq_lens[:rem] = bsl[first:]
            rb.masks[:rem] = masks_t[first:]
            rb.actions[:rem] = ba[first:]
            rb.rewards[:rem] = rewards_t[first:]
        rb.pos = end % rb.capacity
        rb.size = min(rb.size + total, rb.capacity)


# ---------------------------------------------------------------------------
# Suit augmentation (24x) — apply random suit permutation to training batch
# ---------------------------------------------------------------------------
_SUIT_PERM_GPU = None
_ACTION_PERM_GPU = None


def augment_batch(batch, device):
    """Apply random suit permutation to each sample in batch (in-place)."""
    global _SUIT_PERM_GPU, _ACTION_PERM_GPU
    if _SUIT_PERM_GPU is None:
        _SUIT_PERM_GPU = SUIT_PERM_T.to(device)       # [24, 4]
        _ACTION_PERM_GPU = ACTION_PERM_TABLE.to(device)  # [24, 43]

    B = batch["suits"].shape[0]
    # Pick random permutation per sample
    perm_idx = torch.randint(24, (B,), device=device)

    # Permute suit_ids: map 0-3 through perm, leave 4 (S_NULL) unchanged
    suit_perm = _SUIT_PERM_GPU[perm_idx]  # [B, 4]
    suits = batch["suits"]  # [B, L]
    is_real_suit = suits < 4  # mask for non-NULL suits
    # Gather: for each position, look up suit_perm[b, old_suit]
    permuted = torch.gather(suit_perm, 1, suits.clamp(0, 3))  # [B, L]
    batch["suits"] = torch.where(is_real_suit, permuted, suits)

    # Permute actions
    action_perm = _ACTION_PERM_GPU[perm_idx]  # [B, 43]
    old_actions = batch["actions"]  # [B]
    batch["actions"] = torch.gather(action_perm, 1, old_actions.unsqueeze(1)).squeeze(1)


# ---------------------------------------------------------------------------
# Action selection
# ---------------------------------------------------------------------------
@torch.no_grad()
def select_actions(model, primary, suits, pad_mask, action_mask, eps):
    with torch.amp.autocast("cuda", dtype=torch.bfloat16):
        logits = model(primary, suits, pad_mask)
    logits = logits.float().masked_fill(action_mask == 0, -1e9)
    greedy = logits.argmax(dim=-1).cpu().numpy()
    mask_np = action_mask.cpu().numpy()
    rand_mask = np.random.random(len(greedy)) < eps
    for i in np.where(rand_mask)[0]:
        greedy[i] = np.random.choice(np.where(mask_np[i] > 0)[0])
    return greedy


